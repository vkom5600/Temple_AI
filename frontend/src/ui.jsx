export function Icon({ name, size = 18 }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      {P[name]}
    </svg>
  )
}

export const Badge = ({ tone = 'neutral', children }) => <span className={`badge badge-${tone}`}>{children}</span>

export function StatusBadge({ task }) {
  if (task.status === 'todo') return isOverdue(task) ? <Badge tone="red">Overdue</Badge> : <Badge>To do</Badge>
  if (task.status === 'awaiting') return <Badge tone="amber">Waiting for sign-off</Badge>
  if (task.status === 'verified') return <Badge tone="green">Signed off</Badge>
  if (task.status === 'done') return <Badge tone="green">Done</Badge>
  if (task.status === 'flagged') return <Badge tone="red">Couldn't do</Badge>
  return null
}

export function DueText({ task }) {
  const d = fmtDay(task.due)
  return <span>{d === 'Today' ? '' : d + ', '}{fmtTime(task.due)}</span>
}

export function Avatar({ user, size = 36 }) {
  const hue = [...user.name].reduce((a, c) => a + c.charCodeAt(0), 0) % 360
  return (
    <span className="avatar" style={{ width: size, height: size, fontSize: size * 0.42, background: `hsl(${hue} 45% 88%)`, color: `hsl(${hue} 45% 28%)` }}>
      {user.name[0]}
    </span>
  )
}

export function Modal({ title, onClose, children, footer, wide }) {
  useEffect(() => {
    const k = (e) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', k)
    return () => window.removeEventListener('keydown', k)
  }, [onClose])
  return (
    <div className="overlay" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`modal ${wide ? 'modal-wide' : ''}`} role="dialog" aria-modal="true" aria-label={title}>
        <div className="modal-head">
          <h2>{title}</h2>
          <button className="icon-btn" onClick={onClose} aria-label="Close"><Icon name="x" /></button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  )
}

export function Empty({ icon = 'inbox', children }) {
  return (
    <div className="empty">
      <Icon name={icon} size={22} />
      <div>{children}</div>
    </div>
  )
}

export function CopyButton({ text, label = 'Copy' }) {
  const copy = async (e) => {
    const btn = e.currentTarget
    try {
      await navigator.clipboard.writeText(text)
      btn.dataset.done = '1'
      setTimeout(() => delete btn.dataset.done, 1500)
    } catch {
      /* clipboard can be blocked; user can still select the text */
    }
  }
  return (
    <button className="btn btn-ghost copy-btn" onClick={copy}>
      <Icon name="copy" size={16} /> <span className="copy-label">{label}</span><span className="copy-done">Copied</span>
    </button>
  )
}
